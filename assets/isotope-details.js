// NMR periodic-table values win on overlapping nuclides; extras remain inspector-only.
export function inspectorIsotopes(element){
  const list=new Map((isotopeCatalogue[element.symbol]||[]).map(i=>[String(i.mass),i]));
  for(const i of element.isotopes||[]){
    const mass=Number(i.mass);
    if(!Number.isInteger(mass)||mass<=0)continue;
    list.set(String(mass),{...list.get(String(mass)),...i});
  }
  return [...list.values()].sort((a,b)=>Number(a.mass)-Number(b.mass));
}
